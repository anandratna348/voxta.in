import { Quote, Sparkles } from "lucide-react";
import { CopyButton } from "@/components/ui/CopyButton";
import { EmptyState } from "@/components/ui/Feedback";
import { FormattedAnswer } from "./FormattedAnswer";
import { formatDateTime } from "@/lib/format";
import type { StoredAnswer } from "@/lib/copilotStore";

export function AnswerHero({ answer, auto }: { answer: StoredAnswer | null; auto: boolean }) {
  if (!answer) {
    return (
      <EmptyState
        icon={<Sparkles className="h-6 w-6" />}
        title="No suggested answer yet"
        description={
          auto
            ? "Auto detect is on. When an interviewer question appears in the transcript, the answer shows here."
            : "Check the transcript for questions, or ask about a specific question from the panel on the right."
        }
      />
    );
  }
  return (
    <section aria-label="Suggested answer" className="overflow-hidden rounded-xl2 border border-lavender-200 bg-paper-raised shadow-lift">
      <header className="flex items-center justify-between gap-4 bg-lavender-50 px-7 py-4">
        <div className="flex items-center gap-2 text-sm font-semibold text-indigo-700">
          <Sparkles className="h-4 w-4" />
          Suggested answer
          <span className="font-normal text-indigo-400">{formatDateTime(answer.createdAt)}</span>
        </div>
        <CopyButton text={answer.answer} />
      </header>
      <div className="px-7 py-6">
        <div className="mb-5 flex gap-3 rounded-xl bg-paper px-4 py-3 text-sm text-indigo-600">
          <Quote className="mt-0.5 h-4 w-4 shrink-0 text-lavender-400" />
          <p className="line-clamp-3">{answer.question}</p>
        </div>
        <FormattedAnswer text={answer.answer} />
      </div>
      <footer className="border-t border-paper-line px-7 py-3 text-xs text-indigo-400">
        {answer.source === "backend"
          ? "Saved in the meeting history from a full transcript analysis."
          : "Stored on this computer. Review it before you use it, since it is generated by an AI model."}
      </footer>
    </section>
  );
}